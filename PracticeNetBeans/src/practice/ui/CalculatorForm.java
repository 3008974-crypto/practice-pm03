    private void calculate(char operation) {
    try {
        double first = Double.parseDouble(
                firstNumberField.getText().trim().replace(',', '.'));
        double second = Double.parseDouble(
                secondNumberField.getText().trim().replace(',', '.'));

        if (!Double.isFinite(first) || !Double.isFinite(second)) {
            resultLabel.setText("Ошибка: введите конечные числа.");
            return;
        }

        double result;

        switch (operation) {
            case '+':
                result = first + second;
                break;
            case '-':
                result = first - second;
                break;
            case '*':
                result = first * second;
                break;
            case '/':
                if (second == 0) {
                    resultLabel.setText("Ошибка: деление на ноль.");
                    return;
                }
                result = first / second;
                break;
            default:
                resultLabel.setText("Ошибка: неизвестная операция.");
                return;
        }

        if (!Double.isFinite(result)) {
            resultLabel.setText("Ошибка: результат вне диапазона.");
            return;
        }

        resultLabel.setText("Результат: " + result);
    } catch (NumberFormatException exception) {
        resultLabel.setText("Ошибка: введите два числа.");
    }
}


